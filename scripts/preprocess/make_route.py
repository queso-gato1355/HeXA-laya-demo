"""Generate the hard-coded route data for the dashboard from the preprocessing outputs.

  python make_route.py <clip_id>       -> src/data/routes/<clip_id>.ts  (+ regenerates src/data/routes/index.ts)
  python make_route.py                 -> only src/data/routes/index.ts

Inputs: data/<clip>/gps.json (pick_clip.py cut), data/<clip>/heading.json (heading.py, optional),
annotations/<clip>.json (hand-labelled crossings, optional), clips.json (label / description / order).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from common import ROOT

ACCURACY_M = 4.0  # FrodoBots GPS has no accuracy column; fixed 4 m is a demo assumption
HERE = Path(__file__).parent
ROUTES = ROOT / "src" / "data" / "routes"


def catalog() -> list[dict]:
    return json.loads((HERE / "clips.json").read_text(encoding="utf-8"))["clips"]


def ident(clip_id: str) -> str:
    return clip_id.replace("-", "_")


def js(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def write_clip(clip_id: str) -> None:
    info = next((c for c in catalog() if c["clipId"] == clip_id), {"label": clip_id, "description": ""})
    meta = json.loads((ROOT / "data" / clip_id / "gps.json").read_text(encoding="utf-8"))
    ann_p = HERE / "annotations" / f"{clip_id}.json"
    crossings = json.loads(ann_p.read_text(encoding="utf-8"))["crossings"] if ann_p.exists() else []
    dur = meta["duration"]
    pts = [p for p in meta["gps"] if -2.5 <= p["t"] <= dur + 2.5]
    last = pts[-1]
    head_p = ROOT / "data" / clip_id / "heading.json"
    head = json.loads(head_p.read_text(encoding="utf-8")) if head_p.exists() else None

    route = "\n".join(f"    {{ t: {p['t']:.2f}, lat: {p['lat']:.6f}, lon: {p['lon']:.6f}, accuracyM: {ACCURACY_M} }}," for p in pts)
    cross = "\n".join(f"    {{ tStart: {c['tStart']:.1f}, tEnd: {c['tEnd']:.1f} }}, // {c.get('note', '')}" for c in crossings)
    if head:
        cal = head["calibration"]
        heading = ", ".join(f"[{t:.1f}, {d:.1f}]" for t, d in zip(head["t"], head["deg"]))
        head_doc = (f"compass (hard-iron calibrated, aligned to GPS course: median residual {cal['residualMedDeg']} deg) "
                    f"fused with camera yaw, {head['hz']:g} Hz, tau {head['tauS']:g} s")
        head_src = head["source"]
    else:
        heading, head_doc, head_src = "", "none: the dashboard falls back to GPS course", "gps"

    src = f"""// GENERATED by scripts/preprocess/make_route.py — do not edit by hand (edit annotations/ or clips.json and re-run).
// Source: FrodoBots-2K (CC-BY-SA-4.0) part {meta['part']}, {meta['ride']}, start epoch {meta['startEpoch']}.
import type {{ ClipRoute }} from "./types";

export const {ident(clip_id)}: ClipRoute = {{
  clipId: {js(clip_id)},
  label: {js(info['label'])},
  description: {js(info['description'])},
  durationS: {dur},
  source: {js(f"FrodoBots-2K part {meta['part']} {meta['ride']} @ {meta['startEpoch']}")},
  // 1 Hz GPS, t = seconds from clip start; accuracyM fixed {ACCURACY_M} m (demo assumption)
  route: [
{route}
  ],
  destination: {{ lat: {last['lat']:.6f}, lon: {last['lon']:.6f} }},
  // hand-labelled road / junction crossings (scripts/preprocess/annotations/{clip_id}.json)
  crossings: [
{cross}
  ],
  // heading: {head_doc}; [t, deg]
  headingSource: {js(head_src)},
  heading: [{heading}],
}};
"""
    ROUTES.mkdir(parents=True, exist_ok=True)
    (ROUTES / f"{clip_id}.ts").write_text(src, encoding="utf-8")
    print(f"wrote src/data/routes/{clip_id}.ts ({len(pts)} points, {len(crossings)} crossings, heading {head_src})")


def write_index() -> None:
    ids = [c["clipId"] for c in catalog() if (ROUTES / f"{c['clipId']}.ts").exists()]
    imports = "\n".join(f'import {{ {ident(i)} }} from "./{i}";' for i in ids)
    src = f"""// GENERATED by scripts/preprocess/make_route.py from clips.json — the demo clip registry.
{imports}
import type {{ ClipRoute }} from "./types";

export const CLIPS: ClipRoute[] = [{", ".join(ident(i) for i in ids)}];
export const DEFAULT_CLIP_ID = {js(ids[0])};

export function getClip(id: string | null | undefined): ClipRoute {{
  return CLIPS.find((c) => c.clipId === id) ?? CLIPS[0];
}}

export type {{ ClipRoute, Crossing, GpsPoint }} from "./types";
"""
    (ROUTES / "index.ts").write_text(src, encoding="utf-8")
    print(f"wrote src/data/routes/index.ts ({len(ids)} clips)")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("clip_id", nargs="?")
    a = ap.parse_args()
    if a.clip_id:
        write_clip(a.clip_id)
    write_index()


if __name__ == "__main__":
    main()
